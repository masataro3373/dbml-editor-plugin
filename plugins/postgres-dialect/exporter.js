// 日本語コメント: PostgreSQL DDL エクスポーター実装 (plugins/postgres-dialect/exporter.js)

import { ddlExportTemplate } from './ddl-template.js';

export function createPostgresExporter(config = {}, ejs, context) {
  const BaseExporter = context?.api?.BaseExporter || class {
    constructor(cfg) { this.config = cfg; }
  };

  return new class PostgresExporter extends BaseExporter {
    constructor() {
      super(config);
    }

    async preprocess(model, options = {}) {
      const rawTables = model?.tables || [];
      const rawRefs = model?.refs || [];
      const project = model?.project || {};

      let targetTables = rawTables;
      if (Array.isArray(options.targetTableNames) && options.targetTableNames.length > 0) {
        const targetSet = new Set(options.targetTableNames.map(n => n.toUpperCase()));
        targetTables = rawTables.filter(t => targetSet.has(t.name.toUpperCase()));
      }

      const normalizedTables = targetTables.map(tbl => {
        const fields = (tbl.fields || []).map(f => {
          const isPk = Boolean(f.pk);
          let noteStr = f.note;
          if (typeof noteStr === 'object' && noteStr !== null) noteStr = noteStr.value || '';

          return {
            name: f.name,
            type: f.type || 'VARCHAR(255)',
            pk: isPk,
            notNull: Boolean(f.not_null) || isPk,
            increment: Boolean(f.increment),
            dbdefault: f.dbdefault ?? null,
            note: noteStr || '',
            logicalName: f.logicalName || f.custom?.logicalName || '',
          };
        });

        const indexes = (tbl.indexes || []).map(idx => {
          const cols = (idx.columns || idx.fields || []).map(c => {
            if (typeof c === 'object' && c !== null) return c.name || c.value || '';
            return String(c);
          });
          return {
            name: idx.name,
            unique: Boolean(idx.unique),
            pk: Boolean(idx.pk),
            type: idx.type,
            columns: cols,
          };
        });

        let tblNote = tbl.note;
        if (typeof tblNote === 'object' && tblNote !== null) tblNote = tblNote.value || '';

        return {
          name: tbl.name,
          logicalName: tbl.logicalName || tbl.custom?.logicalName || '',
          note: tblNote || '',
          fields,
          columns: fields,
          indexes,
          checks: tbl.checks || [],
          custom: tbl.custom || {},
        };
      });

      return {
        project,
        tables: normalizedTables,
        refs: rawRefs,
      };
    }

    async process(data, options = {}) {
      if (!ejs || typeof ejs.render !== 'function') {
        throw new Error('EJS ライブラリが利用できません (requires: ["ejs"])');
      }

      const ejsOptions = {
        includeDelete: options.includeDelete ?? false,
        deletePosition: options.deletePosition ?? 'top',
        includeComment: options.includeComment ?? true,
        commentPosition: options.commentPosition ?? 'bottom',
        commentSource: options.commentSource ?? 'logicalName',
        includeTablespace: options.includeTablespace ?? true,
      };

      return ejs.render(ddlExportTemplate, {
        tables: data.tables,
        refs: data.refs,
        project: data.project,
        options: ejsOptions,
      });
    }

    async render(data, options = {}) {
      return this.process(data, options);
    }

    async postprocess(text, context = {}, options = {}) {
      const result = String(text || '').replace(/\r\n/g, '\n').replace(/\n{3,}/g, '\n\n').trim() + '\n';
      const header = `-- ========================================================\n-- Generated by DBML Editor v2 (${config.displayName || 'PostgreSQL'})\n-- Date: ${new Date().toISOString()}\n-- ========================================================\n\n`;
      return {
        content: header + result,
        filename: options.filename || `${config.id || 'postgresql'}.sql`,
      };
    }
  }();
}
